/**
 * Resolve an image `url` to a loadable source. Placeholder/static paths begin
 * with `/` and are returned untouched; everything else is treated as an R2 key
 * and prefixed with the configured public bucket URL.
 *
 * @param url Placeholder path (starts with `/`) or R2 object key.
 * @returns A URL usable directly in `src`/`href`.
 */
export function photoSrc(url: string): string {
	return url.startsWith('/') ? url : getImageUrl(url);
}

