/** Zero-pad a positive integer to two digits (1 -> "01"). */
function pad2(n: number): string {
	return String(n).padStart(2, '0');
}

/**
 * Build a full set of variants where every size/format leaf points at the same
 * placeholder `file` and reports the same intrinsic dimensions. Fresh objects
 * per leaf avoid accidental reference aliasing.
 */
function demoVariants(file: string, width: number, height: number): PhotoVariants {
	const leaf = (): PhotoFormat => ({ url: file, width, height });
	const group = () => ({ avif: leaf(), webp: leaf(), jpg: leaf() });
	return {
		thumb: group(),
		medium: group(),
		large: group(),
		original: group()
	};
}

/**
 * TEMPORARY demo photo set — exactly 24 entries (`demo-01`..`demo-24`).
 * Generated from {@link DEMO_DIMENSIONS}; replace with real ingested photos.
 */
export const demoPhotos: Photo[] = DEMO_DIMENSIONS.map(([width, height], i) => {
	const nn = pad2(i + 1);
	const file = `/placeholders/demo-${nn}.jpg`;
	// Deterministic staggered timestamps: 2026-07-01 + (i + 1) days => 2026-07-02..2026-07-25.
	const stamp = `2026-07-${pad2(i + 2)}T12:00:00.000Z`;
	return {
		id: `demo-${nn}`,
		slug: `demo-${nn}`,
		title: `Frame ${nn}`,
		tags: [],
		collectionIds: [],
		featured: false,
		aspectRatio: width / height,
		variants: demoVariants(file, width, height),
		exif: {},
		createdAt: stamp,
		updatedAt: stamp
	};
});
